def _emit_user_routines(spec: "ProjectSpec", lines: list[str]) -> None:
    lines.append("game_logic:")
    lines.append("\t;; User game logic — edit in routines/game_logic.acme")
    routines_dir = spec.project_dir / "routines"
    if (routines_dir / "game_logic.acme").exists():
        lines.append(f'\t!source "routines/game_logic.acme"')
    else:
        lines.append("\trts")
    lines.append("")

    for r in spec.routines:
        name = Path(r).stem
        if (routines_dir / f"{name}.acme").exists():
            lines.append(f"_{name}:")
            lines.append(f'\t!source "routines/{name}.acme"')
            lines.append("")


def _emit_sprite_data(spec: "ProjectSpec", lines: list[str]) -> None:
    if not spec.sprites:
        return
    lines.append("")
    lines.append(f"* = ${spec.memory.sprite_data:04X}")
    lines.append("")
    for s in spec.sprites:
        lines.append(f";; Sprite {s.index}: {s.name}")
        if s.data_file and (spec.project_dir / s.data_file).exists():
            lines.append(f'\t!bin "{s.data_file}"')
        else:
            lines.append(f"\t+c64_sprite_placeholder {s.index}")
    lines.append("")


def _emit_routines_footer(spec: "ProjectSpec", lines: list[str]) -> None:
    routines_dir = spec.project_dir / "routines"
    if not routines_dir.exists():
        return

    lines.append("")
    lines.append("\t;; -- User routines --")
    for acme_file in sorted(routines_dir.glob("*.acme")):
        name = acme_file.stem
        if name == "game_logic":
            continue
        if name not in spec.routines:
            lines.append(f'\t!source "routines/{acme_file.name}"')


def run_build(spec: "ProjectSpec") -> Path:
    src_dir = get_output_src_dir(spec.project_dir)
    build_dir = get_output_build_dir(spec.project_dir)
    src_dir.mkdir(parents=True, exist_ok=True)
    build_dir.mkdir(parents=True, exist_ok=True)

    asm_code = generate_assembly(spec)
    main_asm = src_dir / "main.acme"
    with open(main_asm, "w") as f:
        f.write(asm_code)

    routines_src = spec.project_dir / "routines"
    routines_dst = src_dir / "routines"
    if routines_src.exists():
        import shutil
        shutil.copytree(routines_src, routines_dst, dirs_exist_ok=True)

    assets_src = spec.project_dir / "assets"
    assets_dst = src_dir / "assets"
    if assets_src.exists():
        import shutil
        shutil.copytree(assets_src, assets_dst, dirs_exist_ok=True)

    return main_asm
